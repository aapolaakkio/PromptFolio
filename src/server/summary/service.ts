import { and, eq } from "drizzle-orm";

import type { ChatClient } from "../chat/runner.ts";
import type { Db } from "../db/index.ts";
import { weeklySummaries } from "../db/schema.ts";
import { withModelTimeout } from "../instruments/find-page.ts";
import { createClient } from "../chat/runner.ts";
import { askForSummary } from "./ask.ts";
import { gatherFacts, SummaryFacts } from "./facts.ts";
import { helsinkiToday } from "./helsinki.ts";

const HOUR_MS = 3_600_000;
/** A refresh pays for a model call, so it is paced on the server. */
const REFRESH_AFTER_MS = 24 * HOUR_MS;
/** A missing text is retried on a later visit, not on every one. */
const RETRY_AFTER_MS = HOUR_MS;

export type WeeklySummary = {
  readonly week: string;
  readonly facts: SummaryFacts;
  /** Null when the model was down or its text failed a check: the page shows the facts. */
  readonly text: string | null;
  readonly canRefresh: boolean;
  /** When a missing text may be tried again (ms since epoch); null when there is a text. */
  readonly retryAt: number | null;
};

/** ISO 8601 week of the Finnish calendar day, "2026-W46". */
export const isoWeek = (date: Date): string => {
  const day = new Date(`${helsinkiToday(date)}T00:00:00Z`);
  // The week belongs to the year of its Thursday.
  day.setUTCDate(day.getUTCDate() + 4 - (day.getUTCDay() || 7));
  const yearStart = Date.UTC(day.getUTCFullYear(), 0, 1);
  const week = Math.ceil(((day.getTime() - yearStart) / 86_400_000 + 1) / 7);
  return `${day.getUTCFullYear()}-W${String(week).padStart(2, "0")}`;
};

const parsedFacts = (stored: string): SummaryFacts | null => {
  try {
    const parsed = SummaryFacts.safeParse(JSON.parse(stored));
    return parsed.success ? parsed.data : null;
  } catch {
    return null;
  }
};

const modelFor = (client: ChatClient | undefined): ChatClient | null => {
  try {
    return withModelTimeout(client ?? createClient());
  } catch {
    // A model that cannot be configured is the same as one that is down.
    return null;
  }
};

type Options = {
  readonly now?: Date;
  readonly refresh?: boolean;
  readonly client?: ChatClient;
};

type Row = typeof weeklySummaries.$inferSelect;

const viewOf = (row: Row, now: Date): WeeklySummary | null => {
  const facts = parsedFacts(row.facts);
  return facts === null
    ? null
    : {
        week: row.week,
        facts,
        text: row.text,
        canRefresh: now.getTime() - row.createdAt.getTime() >= REFRESH_AFTER_MS,
        retryAt: row.text === null ? row.createdAt.getTime() + RETRY_AFTER_MS : null,
      };
};

const textFor = async (client: ChatClient | undefined, facts: SummaryFacts) => {
  const model = modelFor(client);
  return model === null ? null : askForSummary(model, JSON.stringify(facts, null, 2));
};

const rowFor = (db: Db, userId: string, week: string) =>
  db
    .select()
    .from(weeklySummaries)
    .where(and(eq(weeklySummaries.userId, userId), eq(weeklySummaries.week, week)))
    .get();

/** Cached for the ISO week; generated on the first call, retried when the text is missing, regenerated by an explicit refresh at most once a day. Only the request that claims the row calls the model. */
export const getWeeklySummary = async (
  db: Db,
  userId: string,
  options: Options = {},
): Promise<WeeklySummary> => {
  const now = options.now ?? new Date();
  const week = isoWeek(now);
  const row = await rowFor(db, userId, week);
  const cached = row === undefined ? null : viewOf(row, now);
  const key = and(eq(weeklySummaries.userId, userId), eq(weeklySummaries.week, week));

  if (row !== undefined && cached !== null) {
    const age = now.getTime() - row.createdAt.getTime();
    const refreshing = options.refresh === true && age >= REFRESH_AFTER_MS;
    const retrying = row.text === null && age >= RETRY_AFTER_MS;
    if (!refreshing && !retrying) return cached;

    // Moving createdAt only if nobody else has: the winner alone asks the model, and the day's refresh is spent either way.
    const claimed = await db
      .update(weeklySummaries)
      .set({ createdAt: now })
      .where(and(key, eq(weeklySummaries.createdAt, row.createdAt)))
      .returning({ week: weeklySummaries.week })
      .all();
    if (claimed.length === 0) {
      const current = await rowFor(db, userId, week);
      return (current && viewOf(current, now)) ?? { ...cached, canRefresh: false };
    }
    const nextTry = now.getTime() + RETRY_AFTER_MS;
    const facts = await gatherFacts(db, userId, now);
    const text = await textFor(options.client, facts);
    if (text === null) {
      // A failed attempt must not replace a good note or the facts it was written from.
      if (row.text !== null) return { ...cached, canRefresh: false };
      // With no note to protect, the facts shown should at least be current.
      await db
        .update(weeklySummaries)
        .set({ facts: JSON.stringify(facts) })
        .where(key)
        .run();
      return { week, facts, text: null, canRefresh: false, retryAt: nextTry };
    }
    await db
      .update(weeklySummaries)
      .set({ facts: JSON.stringify(facts), text })
      .where(key)
      .run();
    return { week, facts, text, canRefresh: false, retryAt: null };
  }

  const facts = await gatherFacts(db, userId, now);
  const stored = { userId, week, facts: JSON.stringify(facts), text: null, createdAt: now };
  if (row !== undefined) {
    // A row whose facts cannot be read is replaced, not claimed.
    await db
      .insert(weeklySummaries)
      .values(stored)
      .onConflictDoUpdate({
        target: [weeklySummaries.userId, weeklySummaries.week],
        set: { facts: stored.facts, text: null, createdAt: now },
      })
      .run();
  } else {
    const inserted = await db
      .insert(weeklySummaries)
      .values(stored)
      .onConflictDoNothing()
      .returning({ week: weeklySummaries.week })
      .all();
    if (inserted.length === 0) {
      const current = await rowFor(db, userId, week);
      return (
        (current && viewOf(current, now)) ?? {
          week,
          facts,
          text: null,
          canRefresh: false,
          retryAt: now.getTime() + RETRY_AFTER_MS,
        }
      );
    }
  }
  const text = await textFor(options.client, facts);
  if (text !== null) await db.update(weeklySummaries).set({ text }).where(key).run();
  return {
    week,
    facts,
    text,
    canRefresh: false,
    retryAt: text === null ? now.getTime() + RETRY_AFTER_MS : null,
  };
};
